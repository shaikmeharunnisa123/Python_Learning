# Concept                 Why do we use it?

# for loop                To process items repeatedly

# in                      To iterate through a sequence

# Loop variable (i)       To hold the current item

# range()                 To generate a sequence of numbers

# Step value              To control the gap or direction

# if inside a loop        To process only values that meet a condition

fruits = ["Apple", "Mango", "Banana"]
for fruit in fruits:
    print(fruit)

for i in range(1,11):
    print(i,end=" ")
    print()